/** Combined token list for all supported chains */
export const TOKEN_LIST: TokenInfo[] = [...ETHEREUM_TOKENS, ...OPTIMISM_TOKENS];

/** Get tokens filtered by chain ID */
export const getTokensByChainId = (chainId: number): TokenInfo[] => {
  return TOKEN_LIST.filter((token) => token.chainId === chainId);
};

/** Find a token by address and chain ID in the static list */
export const findTokenByAddress = (address: string, chainId: number): TokenInfo | undefined => {
  const normalizedAddress = address.toLowerCase();
  return TOKEN_LIST.find((token) => token.chainId === chainId && token.address.toLowerCase() === normalizedAddress);
};
